"""Task B and Task C visualizations.

Streams the JSONL outputs once to compute exact label distributions, then
plots:
  - Task B label-frequency per query (fraction of bins=1)
  - Task C claim-by-label heatmap and class distribution
  - Per-condition Task C example panel showing the structured measurement,
    the claim text, and the label generated by task_C.py
"""

import json
import os
from collections import Counter, defaultdict

import numpy as np
import pandas as pd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = "D:/Coding/MU/Tri-Modal_ECG"
TASK_B = os.path.join(ROOT, "processed", "taskB_temporal_grounding.jsonl")
TASK_C = os.path.join(ROOT, "processed", "taskC_plausibility.jsonl")
INDEX = os.path.join(ROOT, "processed", "index", "index_clean_with_measurements.parquet")
EX = os.path.join(ROOT, "report_assets", "examples.json")
OUT_DIR = os.path.join(ROOT, "report_assets")

plt.rcParams.update({
    "figure.dpi": 130,
    "savefig.dpi": 150,
    "font.size": 10.5,
    "axes.titlesize": 11.5,
    "axes.labelsize": 10.5,
    "axes.spines.top": False,
    "axes.spines.right": False,
})


def save(fig, name):
    p = os.path.join(OUT_DIR, name)
    fig.savefig(p, bbox_inches="tight")
    plt.close(fig)
    print("wrote", p)


# ---------------------------------------------------------------------------
# Pass 1: stream Task B JSONL and accumulate per-query bin statistics
# ---------------------------------------------------------------------------
print("Streaming Task B...")
b_query_total = Counter()
b_query_pos_rows = Counter()  # rows with at least one bin=1
b_query_bin_pos = defaultdict(lambda: np.zeros(10, dtype=np.int64))
b_split = Counter()

with open(TASK_B, "r", encoding="utf-8") as f:
    for line in f:
        rec = json.loads(line)
        q = rec["query"]
        b_query_total[q] += 1
        labels = rec["labels"]
        if any(labels):
            b_query_pos_rows[q] += 1
        b_query_bin_pos[q] += np.asarray(labels, dtype=np.int64)
        b_split[rec["split"]] += 1

print("Task B totals:", b_query_total)
print("Task B all-positive rows:", b_query_pos_rows)
print("Task B split:", b_split)


# ---------------------------------------------------------------------------
# Task B: per-query positive fraction and per-bin positive heatmap
# ---------------------------------------------------------------------------
queries = ["HIGH_HEART_RATE", "LOW_HEART_RATE", "WIDE_QRS"]
fig, axes = plt.subplots(1, 2, figsize=(12, 4.4))

ax = axes[0]
totals = [b_query_total[q] for q in queries]
pos_rows = [b_query_pos_rows[q] for q in queries]
neg_rows = [t - p for t, p in zip(totals, pos_rows)]
x = np.arange(len(queries))
w = 0.38
ax.bar(x - w / 2, pos_rows, w, label="rows with any bin = 1",
       color="#54a24b", edgecolor="black")
ax.bar(x + w / 2, neg_rows, w, label="all-zero rows",
       color="#aaaaaa", edgecolor="black")
for i, (p, n) in enumerate(zip(pos_rows, neg_rows)):
    ax.text(i - w / 2, p + 8000, f"{p:,}", ha="center", fontsize=9, weight="bold")
    ax.text(i + w / 2, n + 8000, f"{n:,}", ha="center", fontsize=9, weight="bold")
ax.set_xticks(x)
ax.set_xticklabels(queries)
ax.set_ylabel("Rows")
ax.set_title("Task B label split per query (799,706 studies x 3 queries)")
ax.set_ylim(0, max(totals) * 1.12)
ax.legend(loc="upper right")
ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{int(v):,}"))

ax = axes[1]
mat = np.vstack([b_query_bin_pos[q] for q in queries])
mat_frac = mat / np.maximum(np.array(totals)[:, None], 1)
im = ax.imshow(mat_frac, aspect="auto", cmap="Greens", vmin=0, vmax=mat_frac.max() * 1.05)
ax.set_xticks(range(10))
ax.set_xticklabels([f"bin{i}" for i in range(10)])
ax.set_yticks(range(len(queries)))
ax.set_yticklabels(queries)
for i in range(mat_frac.shape[0]):
    for j in range(mat_frac.shape[1]):
        ax.text(j, i, f"{mat_frac[i, j]:.2f}", ha="center", va="center",
                fontsize=8.5,
                color="white" if mat_frac[i, j] > mat_frac.max() * 0.5 else "#222")
ax.set_title("Per-bin positive fraction (Task B uses local per-bin\ndetection -> per-query fractions vary across bins)")
fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
fig.tight_layout()
save(fig, "fig_taskB_distribution.png")


# ---------------------------------------------------------------------------
# Pass 2: stream Task C JSONL
# ---------------------------------------------------------------------------
print("Streaming Task C...")
c_label = Counter()
c_claim = Counter()
c_pair = Counter()
c_split = Counter()

with open(TASK_C, "r", encoding="utf-8") as f:
    for line in f:
        rec = json.loads(line)
        c_label[rec["label"]] += 1
        c_claim[rec["claim"]] += 1
        c_pair[(rec["claim"], rec["label"])] += 1
        c_split[rec["split"]] += 1

print("Task C label:", c_label)
print("Task C claim:", c_claim)
print("Task C split:", c_split)


# ---------------------------------------------------------------------------
# Task C: label distribution + claim distribution + heatmap
# ---------------------------------------------------------------------------
fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.4))
ax = axes[0]
labs = ["SUPPORTED", "CONTRADICTED", "UNCERTAIN"]
vals = [c_label[l] for l in labs]
colors = ["#54a24b", "#d62728", "#888888"]
bars = ax.bar(labs, vals, color=colors, edgecolor="black")
for bar, v in zip(bars, vals):
    ax.text(bar.get_x() + bar.get_width() / 2, v + max(vals) * 0.012, f"{v:,}",
            ha="center", fontsize=10, weight="bold")
ax.set_title(f"Task C label distribution ({sum(vals):,} rows)")
ax.set_ylabel("Rows")
ax.set_ylim(0, max(vals) * 1.12)
ax.set_yscale("symlog", linthresh=1)
ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{int(v):,}"))

ax = axes[1]
claims_sorted = sorted(c_claim.items(), key=lambda x: -x[1])
names = [c[0] for c in claims_sorted]
counts = [c[1] for c in claims_sorted]
bars = ax.barh(names, counts, color="#4c78a8", edgecolor="black")
for bar, v in zip(bars, counts):
    ax.text(v + max(counts) * 0.01, bar.get_y() + bar.get_height() / 2,
            f"{v:,}", va="center", fontsize=9.5)
ax.invert_yaxis()
ax.set_title("Task C claim distribution")
ax.set_xlabel("Rows")
ax.xaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{int(v):,}"))
fig.tight_layout()
save(fig, "fig_taskC_distribution.png")


# Heatmap claim x label
claim_order = [c for c, _ in claims_sorted]
label_order = ["SUPPORTED", "CONTRADICTED", "UNCERTAIN"]
mat = np.zeros((len(claim_order), len(label_order)), dtype=np.int64)
for i, claim in enumerate(claim_order):
    for j, lab in enumerate(label_order):
        mat[i, j] = c_pair.get((claim, lab), 0)

fig, ax = plt.subplots(figsize=(9, 5.0))
im = ax.imshow(np.log10(mat + 1), aspect="auto", cmap="viridis")
ax.set_xticks(range(len(label_order)))
ax.set_xticklabels(label_order)
ax.set_yticks(range(len(claim_order)))
ax.set_yticklabels(claim_order)
for i in range(mat.shape[0]):
    for j in range(mat.shape[1]):
        ax.text(j, i, f"{mat[i, j]:,}", ha="center", va="center",
                fontsize=9, color="white" if mat[i, j] > mat.max() * 0.05 else "#222")
ax.set_title("Task C: claims x labels (counts)\n"
             "color = log10(count + 1)")
cbar = fig.colorbar(im, ax=ax, fraction=0.05, pad=0.04)
cbar.set_label("log10(count + 1)")
fig.tight_layout()
save(fig, "fig_taskC_heatmap.png")


# ---------------------------------------------------------------------------
# Task C example: walk through one tachycardic study and show the claims
# ---------------------------------------------------------------------------
with open(EX) as f:
    examples = json.load(f)


def task_c_predict(rr, qrs_dur, axis):
    rows = []
    if rr is None or rr <= 0:
        rows.append(("tachycardia present", "UNCERTAIN"))
        rows.append(("bradycardia present", "UNCERTAIN"))
    else:
        hr = 60000 / rr
        if hr > 100:
            rows.append(("tachycardia present", "SUPPORTED"))
            rows.append(("bradycardia present", "CONTRADICTED"))
        elif hr < 60:
            rows.append(("tachycardia present", "CONTRADICTED"))
            rows.append(("bradycardia present", "SUPPORTED"))
        else:
            rows.append(("tachycardia present", "CONTRADICTED"))
            rows.append(("bradycardia present", "CONTRADICTED"))
            rows.append(("normal heart rate", "SUPPORTED"))
    if qrs_dur is None or qrs_dur <= 0:
        rows.append(("wide qrs complex", "UNCERTAIN"))
    elif qrs_dur > 120:
        rows.append(("wide qrs complex", "SUPPORTED"))
        rows.append(("normal qrs duration", "CONTRADICTED"))
    else:
        rows.append(("wide qrs complex", "CONTRADICTED"))
        rows.append(("normal qrs duration", "SUPPORTED"))
    if axis is None:
        rows.append(("axis deviation present", "UNCERTAIN"))
    elif axis < -30:
        rows.append(("left axis deviation", "SUPPORTED"))
        rows.append(("right axis deviation", "CONTRADICTED"))
    elif axis > 90:
        rows.append(("right axis deviation", "SUPPORTED"))
        rows.append(("left axis deviation", "CONTRADICTED"))
    else:
        rows.append(("axis normal", "SUPPORTED"))
    return rows


fig, axes = plt.subplots(2, 2, figsize=(13.5, 7.6))
panels = [("tachycardia", "Tachycardia"), ("bradycardia", "Bradycardia"),
          ("wide_qrs", "Wide QRS"), ("left_axis", "Left axis deviation")]
for ax, (key, label) in zip(axes.flat, panels):
    e = examples[key]
    ax.axis("off")
    ax.set_title(f"{label}  •  study {e['study_id']}", fontsize=11.5,
                 weight="bold", loc="left")
    text = (
        f"Structured measurements:\n"
        f"  rr_interval = {e['rr_interval']:.1f} ms  ->  HR = {e['hr']:.1f} bpm\n"
        f"  qrs_onset = {e['qrs_onset']:.0f}, qrs_end = {e['qrs_end']:.0f}  ->  QRS = {e['qrs_dur']:.0f} ms\n"
        f"  qrs_axis = {e['qrs_axis']:.0f}°\n"
    )
    ax.text(0.02, 0.92, text, transform=ax.transAxes, family="monospace",
            fontsize=9.5, va="top",
            bbox=dict(facecolor="#f4f4f4", edgecolor="#aaa", boxstyle="round,pad=0.4"))
    rows = task_c_predict(e["rr_interval"], e["qrs_dur"], e["qrs_axis"])
    txt_lines = ["Generated Task C rows:"]
    for c, l in rows:
        txt_lines.append(f"  claim='{c}'  ->  label = {l}")
    color_for = {"SUPPORTED": "#1f7a1f", "CONTRADICTED": "#b00020", "UNCERTAIN": "#666"}
    y = 0.55
    ax.text(0.02, y, txt_lines[0], transform=ax.transAxes, fontsize=10,
            weight="bold", va="top")
    y -= 0.07
    for c, l in rows:
        col = color_for[l]
        ax.text(0.02, y,
                f"  claim='{c}'  ->  label = {l}",
                transform=ax.transAxes, family="monospace", fontsize=9.7,
                va="top", color=col)
        y -= 0.06

fig.suptitle("Task C generation walk-through: same physiological measurements drive multiple claim/label rows",
             fontsize=13, weight="bold")
fig.tight_layout()
save(fig, "fig_taskC_walkthrough.png")

print("done")
